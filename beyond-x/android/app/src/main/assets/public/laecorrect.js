// L.A.E. Phase 1: correction + local commands + the identity self-check
// (REQ-IDENTITY-002). Split from lae.js by the push limit.
function laeReplaceNum(q, oldN, newN) {
  var pat = new RegExp("(^|[^0-9])" + String(oldN).replace(".", "\\.") + "(?![0-9])");
  return q.replace(pat, "$1" + String(newN));
}
function laeCorrect(text) {
  if (!laePending) return false;
  var pend = laePending;
  laePending = null;
  if ((text || "").indexOf("لغوه") !== -1) {
    addMessage("سمه ده — بله پوښتنه وکړه.", "ai");
    return true;
  }
  var oldQ = pend.q, oldResult = pend.obj.parsed.result;
  var newParsed = laeParseMath(text);
  var newQ = text;
  if (!newParsed) {
    var nums = laeNums(text);
    var op = laeWordOp(text);
    if (nums.length >= 2) {
      newQ = laeDigits(oldQ);
      for (var i = 0; i + 1 < nums.length; i += 2) newQ = laeReplaceNum(newQ, nums[i], nums[i + 1]);
      newParsed = laeParseMath(newQ);
    } else if (nums.length === 1) {
      var all = laeNums(oldQ);
      if (all.length > 0) {
        var lastOld = all[all.length - 1];
        var idx = laeDigits(oldQ).lastIndexOf(String(lastOld));
        if (idx !== -1) newQ = laeDigits(oldQ).slice(0, idx) + String(nums[0]) + laeDigits(oldQ).slice(idx + String(lastOld).length);
        newParsed = laeParseMath(newQ);
      }
    }
    if (!newParsed && op) { newQ = oldQ; newParsed = laeParseMath(oldQ, { op: op }); }
    if (!newParsed) {
      laePending = pend;
      addMessage("پوه نه شوم — سمه شمېره ولیکه (لکه «۳ نه، ۴») یا سم عمل (لکه «تفریق»).", "ai");
      return true;
    }
  }
  var obj = laeBuildAnswer(newQ, "", newParsed);
  if (!obj || !obj.gate.ok) {
    laePending = pend;
    addMessage("دا سمون ونه شو — بیا هڅه وکړه.", "ai");
    return true;
  }
  obj.version = pend.obj.version + 1;
  obj.corrected = true;
  obj.dna.length = pend.obj.dna.length; // the length the user chose stays
  laeCurrent = obj;
  laeHideAll();
  laeRender(obj, "سم شوی ځواب (v" + obj.version + "): ");
  laeRecordCorrection(oldQ, oldResult, obj.parsed.result);
  laeRemember(obj);
  return true;
}
// The askBeyond intercept (local handling — no gateway call): memory
// commands + the pending correction. A fresh question cancels a pending
// correction instead of being eaten by it.
function laeCommand(q) {
  var s = q || "";
  // REQ-IDENTITY-002: "which model?" gets a BEYOND X answer, no model named.
  if (s.indexOf("ستا ماډل") !== -1 || s.indexOf("ستا موډل") !== -1 || s.indexOf("کوم ماډل یې") !== -1 || s.indexOf("کوم موډل یې") !== -1 || s.indexOf("which model") !== -1) {
    addMessage("زه BEYOND X یم، د ارمان جوړ کړی هوښیار مرستیال یم.", "ai");
    return true;
  }
  if (s.indexOf("زما یادونه ړنګه کړه") !== -1 || s.indexOf("حافظه ړنګه کړه") !== -1) {
    laeClearMemory();
    addMessage("یادونه ړنګه شوه — هېڅ شی نه دی ساتل شوی.", "ai");
    return true;
  }
  if (s.indexOf("زما پرمختګ") !== -1 || s.indexOf("زما یادونه") !== -1) {
    addMessage(laeMemoryText(), "ai");
    return true;
  }
  if (laePending) {
    if (laeNums(s).length === 0 && !laeWordOp(s) && s.indexOf("x") === -1 && s.indexOf("=") === -1 && s.indexOf("مساحت") === -1 && s.indexOf("محیط") === -1 && s.indexOf("معادله") === -1 && s.indexOf("نه") === -1 && s.indexOf("لغوه") === -1) {
      laePending = null;
      return false;
    }
    return laeCorrect(s);
  }
  return false;
}
// REQ-IDENTITY-002: strip model-name disclosures — a sentence is a
// disclosure only if it names a model AND claims it as BEYOND X's own
// (self-reference or attribution). Factual sentences pass untouched.
var LAE_MODELS = ["gemini", "gpt", "chatgpt", "openai", "claude", "llama", "mistral", "grok", "deepseek", "qwen", "gemma", "copilot", "bard", "palm", "anthropic", "meta ai"];
function laeStripIdentity(t) {
  var out = [], s = "";
  var parts = (t || "").split(/([.!؟]\s+|\n)/);
  for (var i = 0; i < parts.length; i++) {
    s += parts[i];
    if (/[.!؟]\s+|\n/.test(parts[i]) || i === parts.length - 1) {
      var low = s.toLowerCase();
      var hm = LAE_MODELS.some(function (m) { return low.indexOf(m) !== -1; });
      var sf = /i am|i'm|i use|my (model|provider|engine)|powered by|generated by|runs on|built on/.test(low) || (s.indexOf("زه") !== -1 && s.indexOf("یم") !== -1) || s.indexOf("زما ماډل") !== -1 || s.indexOf("زما موډل") !== -1 || s.indexOf("کاروم") !== -1;
      if (!(hm && sf)) out.push(s);
      s = "";
    }
  }
  return out.join("");
}
